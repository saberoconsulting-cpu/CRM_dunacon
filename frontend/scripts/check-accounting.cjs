const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/accounting.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const context = { exports: {} };
vm.runInNewContext(compiled.outputText, context);
const { invoiceSum, inAccountingYear } = context.exports;
const { invoiceCurrencyAmounts } = context.exports;
const { accountingIndicators } = context.exports;
assert.ok(Object.values(accountingIndicators([], [])).every(value => value === 0), 'Sin registros, todos los indicadores deben estar en cero');
const purchase = { kind: 'purchase', documentType: 'Factura', issuedAt: '2026-10-22', currency: 'PEN', base: 100, igv: 18, exchangeRate: 1, validated: true };
const sale = { ...purchase, kind: 'sale', currency: 'USD', base: 200, igv: 36, exchangeRate: 3.75 };
assert.equal(invoiceSum([purchase], 'total', true), 118);
assert.equal(invoiceSum([sale], 'total', true), 885);
assert.equal(invoiceCurrencyAmounts(sale, 'PEN').join(','), '750,135,885');
assert.equal(invoiceCurrencyAmounts(sale, 'USD').join(','), '200,36,236');
assert.equal(invoiceCurrencyAmounts(purchase, 'USD'), null);
assert.equal(invoiceCurrencyAmounts(purchase, 'PEN').join(','), '100,18,118');
assert.equal(invoiceSum([purchase, sale], 'base', true), 850);
assert.equal(invoiceSum([purchase, sale], 'igv', true), 153);
assert.equal(invoiceSum([purchase, sale], 'total', true), 1003);
const historical = [{ ...sale, base: 100, igv: 18, exchangeRate: 3.75, issuedAt: '2026-10-20' }, { ...sale, base: 100, igv: 18, exchangeRate: 4, issuedAt: '2026-10-21' }];
assert.equal(invoiceSum(historical, 'total', true), 914.5);
assert.equal(invoiceSum(historical, 'total'), 236);
assert.equal(invoiceSum([sale], 'igv', true) - invoiceSum([purchase], 'igv', true), 117);
const credit = { ...purchase, documentType: 'Nota de crédito', base: 20, igv: 3.6 };
assert.ok(Math.abs(invoiceSum([purchase, credit], 'total') - 94.4) < 0.00001);
assert.equal(invoiceSum([purchase, sale].filter(r => r.kind === 'sale'), 'base'), 200);
assert.equal(inAccountingYear(purchase, '2026', 2026), true);
assert.equal(inAccountingYear(purchase, '2025', 2026), false);
assert.equal(inAccountingYear({ ...purchase, issuedAt: '2019-01-01' }, 'recent', 2026), true);
assert.equal(inAccountingYear({ ...purchase, issuedAt: '2018-12-31' }, 'recent', 2026), false);
assert.equal(inAccountingYear({ ...purchase, issuedAt: '2027-01-01' }, 'recent', 2026), false);
assert.equal(inAccountingYear({ ...purchase, issuedAt: '2021-12-31' }, 'all', 2026), true);
console.log('Contabilidad: conversión a soles, IGV, notas de crédito, separación por registro y filtros anuales verificados.');
const cashSource = fs.readFileSync(path.join(__dirname, '../src/lib/accounting-cash.ts'), 'utf8');
const cashContext = { exports: {} };
vm.runInNewContext(ts.transpileModule(cashSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, cashContext);
const { cashLedger, cashMonthly, cashByDocument } = cashContext.exports;
assert.equal(cashByDocument([], '2026').length, 5);
assert.ok(cashByDocument([], '2026').every(row => row.deposit === 0 && row.expense === 0));
const deposit = { id: 'deposit', date: '2026-01-01', documentType: 'Transferencia bancaria', deposit: 2000, expense: 0 };
const expense = { id: 'expense', date: '2026-01-02', documentType: 'Factura', deposit: 0, expense: 30 };
const later = { id: 'later', date: '2026-03-01', documentType: 'Factura', deposit: 0, expense: 27.69 };
const movements = [later, deposit, expense];
const ledger = cashLedger(movements, '2026', 200);
assert.equal(ledger[0].id, 'deposit');
assert.equal(ledger[0].balance, 2200);
assert.equal(ledger[2].balance, 2142.31);
assert.equal(cashMonthly(movements, '2026', 200)[1].initial, 2170);
assert.equal(cashMonthly(movements, '2026', 200)[11].final, 2142.31);
assert.equal(cashMonthly(movements.filter(r => r.id !== 'expense'), '2026', 200)[11].final, 2172.31);
assert.equal(cashMonthly(movements.map(r => r.id === 'expense' ? { ...r, expense: 50 } : r), '2026', 200)[11].final, 2122.31);
assert.equal(cashByDocument(movements, '2026').find(r => r.documentType === 'Factura').expense, 57.69);
assert.equal(cashByDocument(movements, '2026')[0].deposit, 2000);
assert.equal(cashByDocument([{ ...expense, documentType: 'Taxis - Planilla Mov.' }], '2026')[3].expense, 30);
assert.equal(cashLedger([{ ...expense, expense: 0.1 }, { ...expense, expense: 0.2 }], '2026', 0)[1].balance, -0.3);
assert.equal(cashLedger([deposit, expense], '2027', 100).length, 0);
assert.equal(cashMonthly([], '2026', 200)[11].final, 200);
assert.equal(cashLedger([deposit, { ...expense, date: '2026-01-01' }], '2026', 200)[1].balance, 2170);
const fullPurchase = { ...purchase, deduction: 14.16, deductionNumber: '0001', deductionDate: '2026-10-22' };
const fullSale = { ...sale, deduction: 0, deductionNumber: '', deductionDate: '' };
const real = accountingIndicators([fullPurchase, fullSale], [deposit, expense]);
assert.equal(real.sales, 885);
assert.equal(real.salesIgv, 135);
assert.equal(real.purchases, 118);
assert.equal(real.igvBalance, 117);
assert.equal(real.deductionPaid, 14.16);
assert.equal(real.deductionPending, 0);
assert.equal(real.validated, 118);
assert.equal(real.pending, 0);
assert.equal(real.cashPayments, 30);
assert.equal(real.cashDeposits, 2000);
const pending = accountingIndicators([{ ...fullPurchase, validated: false, deductionNumber: '' }], []);
assert.equal(pending.deductionPaid, 0); assert.equal(pending.deductionPending, 14.16);
assert.equal(pending.validated, 0); assert.equal(pending.pending, 118);
const purchaseNote = { ...fullPurchase, documentType: 'Nota de crédito', base: 20, igv: 3.6, deduction: 0 };
const saleNote = { ...fullSale, documentType: 'Nota de crédito', base: 20, igv: 3.6 };
const validation = accountingIndicators([fullPurchase, purchaseNote, saleNote, { ...fullPurchase, documentType: 'Boleta' }], []);
assert.equal(validation.validated, 118, 'Validación no debe incluir boletas ni notas');
assert.equal(validation.creditNotesCount, 2);
assert.equal(validation.creditNotes, 112.1);
assert.equal(invoiceSum([{ ...fullSale, base: 1.01, igv: .18 }, { ...fullSale, documentType: 'Nota de crédito', base: 1.01, igv: .18 }], 'total', true), 0);
assert.ok(Object.values(accountingIndicators([], [])).every(value => value === 0), 'Eliminar todos los registros debe dejar cero');
console.log('Indicadores: cero sin datos, importes reales al cargar, validación solo de facturas, notas, detracciones y Caja Chica verificados.');
console.log('Caja Chica: orden cronológico, arrastre mensual, saldos al editar/eliminar, céntimos y agrupación por documento verificados.');
